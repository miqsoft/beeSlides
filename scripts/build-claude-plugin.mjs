// Builds claude-plugin/ — the BeeSlides plugin for Claude Code outside the
// app — from the files the app itself uses, so the two never drift apart:
//   - skills/        the built-in skills (desktop/src/main/apichat/skills),
//                    with a line saying where the reference docs are
//   - reference/     docs/agents.md and docs/format.md
//   - mcp/launch.mjs desktop/src/mcp/plugin-launch.mjs (picks the visible app
//                    or a hidden instance), mcp/instruction.txt (claudeLaunch.ts
//                    outsideInstruction)
//   - mcp/server.mjs the app's MCP server with the agent areas filled in and
//                    Code Mode off (agenttools.ts), for background mode: it
//                    lists the tools before any app runs
//   - hooks/, types/ the BeeSlides pane, a Claude Code mod
//                    (desktop/src/mcp/claude-mod/, copied as it is)
//   - .mcp.json, .claude-plugin/plugin.json (+ icon.png, the app's), README.md
// The marketplace that lists it is .claude-plugin/marketplace.json at the
// repo root (hand-written).
//
//   node scripts/build-claude-plugin.mjs           write it
//   node scripts/build-claude-plugin.mjs --check   exit 1 if it is out of date
//
// claude-plugin/ is generated: never edit it, change the sources and re-run.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const out = join(root, 'claude-plugin')
const check = process.argv.includes('--check')
const read = (p) => readFileSync(join(root, p), 'utf8')

/** The deck skills; customize-ui changes the app's own UI and stays in the panel. */
const SKILLS = ['build-deck', 'restyle-deck', 'polish-deck', 'slide-designs', 'translate-deck', 'draw-icons']
const NOTE = '_In this plugin: `task` is the Agent tool (subagents), and `read_reference("agents.md")` means reading `reference/agents.md` of the BeeSlides plugin, two folders up from this skill\'s base directory (`../../reference/agents.md`)._\n\n'
const GENERATED = 'Generated by scripts/build-claude-plugin.mjs from the BeeSlides sources — do not edit.'

const version = JSON.parse(read('slides/package.json')).version
const { outsideInstruction } = await import(join(root, 'desktop/src/main/claudeLaunch.ts'))
const { serverWithAgentAreas, serverWithCodeMode } = await import(join(root, 'desktop/src/main/agenttools.ts'))
const MOD = 'desktop/src/mcp/claude-mod'

/** Every file under `dir`, relative to it. */
function listFiles(dir) {
  if (!existsSync(dir)) return []
  return readdirSync(dir, { recursive: true }).map(String)
    .filter((p) => statSync(join(dir, p)).isFile()).map((p) => relative(dir, join(dir, p)).split('\\').join('/'))
}

/** published path → text, or a Buffer for a binary file */
const files = new Map()
files.set('.claude-plugin/icon.png', readFileSync(join(root, 'desktop/build/icon.png')))
files.set('.claude-plugin/plugin.json', JSON.stringify({
  name: 'beeslides',
  version,
  description: 'Build, restyle and polish BeeSlides decks from Claude Code: the deck tools of the running BeeSlides app, and the skills its own Claude panel uses.',
  author: { name: 'The BeeSlides authors' },
  homepage: 'https://miqsoft.github.io/beeSlides/create/outside-apps/',
  repository: 'https://github.com/miqsoft/beeslides',
  license: 'AGPL-3.0-or-later',
  keywords: ['slides', 'presentations', 'beeslides', 'mcp'],
  // the pane's $.state contract (hooks/register.tsx)
  types: './types/index.d.ts',
}, null, 2) + '\n')
files.set('.mcp.json', JSON.stringify({
  mcpServers: { beeslides: { command: 'node', args: ['${CLAUDE_PLUGIN_ROOT}/mcp/launch.mjs'] } },
}, null, 2) + '\n')
files.set('mcp/launch.mjs', read('desktop/src/mcp/plugin-launch.mjs'))
files.set('mcp/instruction.txt', outsideInstruction('@REFDIR@') + '\n')
files.set('mcp/server.mjs', serverWithCodeMode(serverWithAgentAreas(read('desktop/src/mcp/slides-mcp-server.mjs')), false))
for (const p of listFiles(join(root, MOD))) files.set(p, read(`${MOD}/${p}`))
files.set('reference/agents.md', read('docs/agents.md').replace(/__APP_VERSION__/g, version))
files.set('reference/format.md', read('docs/format.md'))
for (const name of SKILLS) {
  const md = read(`desktop/src/main/apichat/skills/${name}.md`)
  files.set(`skills/${name}/SKILL.md`, md.replace(/^(---\n[\s\S]*?\n---\n\n?)/, (head) => head + NOTE))
}
files.set('README.md', `# BeeSlides plugin for Claude Code

<!-- ${GENERATED} -->

Work on BeeSlides decks from Claude Code in your own terminal: build a deck
from a paper or a topic, give a deck a new look, polish it, translate it. The
plugin brings the deck tools of the BeeSlides app, the skills its built-in
Claude panel uses (${SKILLS.join(', ')}), and a BeeSlides pane beside the
chat with the slides Claude looks at and the designs to pick from.

## Set up

1. Install BeeSlides and open it once (again after each update: that is
   how the plugin finds it).
2. In Claude Code:

   \`\`\`
   /plugin marketplace add miqsoft/beeslides
   /plugin install beeslides@beeslides
   \`\`\`

3. Ask Claude Code, e.g. "Build a 12-minute conference talk from paper.pdf
   into talk.beeslides.html".

## With or without the BeeSlides window

- **BeeSlides open** with **Settings ▸ AI chat ▸ Advanced ▸ Allow AI apps
  outside BeeSlides** on: Claude works in the app, on the deck you last
  focused or the file it opens; you watch every change. The first time,
  BeeSlides asks whether to allow Claude Code.
- **Otherwise** Claude starts a hidden BeeSlides for this chat: no window,
  no Dock icon. It opens the deck file it was given, every change is saved
  to that file, and the BeeSlides pane (\`/beeslides\`) shows the slides
  and the designs to pick from. The hidden BeeSlides quits with the chat.

Needs Node.js 18 or newer on your PATH (the plugin's MCP server runs with
\`node\`) and BeeSlides installed: screenshots, measuring and layout happen
in the app. Pictures in the pane need a terminal that shows images (kitty,
Ghostty, iTerm2 3.5+). Version ${version}.

Guide: https://miqsoft.github.io/beeSlides/create/outside-apps/
`)


if (check) {
  const have = listFiles(out)
  const same = (p, want) => (Buffer.isBuffer(want) ? readFileSync(join(out, p)).equals(want) : readFileSync(join(out, p), 'utf8') === want)
  const stale = [...files].filter(([p, want]) => !have.includes(p) || !same(p, want)).map(([p]) => p)
  const extra = have.filter((p) => !files.has(p))
  if (stale.length || extra.length) {
    console.log(`claude-plugin/ is out of date — run node scripts/build-claude-plugin.mjs\n  changed: ${stale.join(', ') || '—'}\n  extra: ${extra.join(', ') || '—'}`)
    process.exit(1)
  }
  console.log(`claude-plugin/ is up to date (${files.size} files)`)
} else {
  rmSync(out, { recursive: true, force: true })
  for (const [p, text] of files) {
    mkdirSync(dirname(join(out, p)), { recursive: true })
    writeFileSync(join(out, p), text)
  }
  console.log(`wrote claude-plugin/ (${files.size} files, version ${version})`)
}
